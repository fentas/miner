//! Bitcoin Core configuration file generation
//!
//! This module handles reading and writing bitcoin.conf files
//! with optimal settings for mining.

use std::path::Path;
use tracing::info;

use super::BitcoinError;

/// Configuration for bitcoin.conf generation
pub struct BitcoinConfig {
    pub rpc_user: String,
    pub rpc_password: String,
    pub rpc_port: u16,
    pub prune_size: u32,
    pub dbcache: u32,
}

impl Default for BitcoinConfig {
    fn default() -> Self {
        Self {
            rpc_user: generate_random_string(16),
            rpc_password: generate_random_string(32),
            rpc_port: 8332,
            prune_size: 10000,
            dbcache: calculate_dbcache(),
        }
    }
}

/// Calculate optimal dbcache size based on available system memory
pub fn calculate_dbcache() -> u32 {
    use sysinfo::System;

    let mut sys = System::new_all();
    sys.refresh_memory();

    let total_mem_mb = sys.total_memory() / (1024 * 1024);
    let available_mem_mb = sys.available_memory() / (1024 * 1024);

    // Use 50% of available memory or 25% of total, whichever is smaller
    // This leaves room for the OS and mining
    let target = ((available_mem_mb / 2) as u32).min((total_mem_mb / 4) as u32);

    // Clamp between 450 MB (default) and 16384 MB (16 GB)
    target.clamp(450, 16384)
}

/// Read existing bitcoin.conf credentials if present
/// Returns Some(config) if valid credentials found, None otherwise
pub fn read_existing_config(data_dir: &Path) -> Option<BitcoinConfig> {
    let config_path = data_dir.join("bitcoin.conf");
    let content = std::fs::read_to_string(&config_path).ok()?;

    let mut config = BitcoinConfig::default();
    let mut found_user = false;
    let mut found_pass = false;

    for line in content.lines() {
        let line = line.trim();
        if line.starts_with("rpcuser=") {
            config.rpc_user = line.trim_start_matches("rpcuser=").to_string();
            found_user = true;
        } else if line.starts_with("rpcpassword=") {
            config.rpc_password = line.trim_start_matches("rpcpassword=").to_string();
            found_pass = true;
        } else if line.starts_with("rpcport=") {
            if let Ok(port) = line.trim_start_matches("rpcport=").parse() {
                config.rpc_port = port;
            }
        }
    }

    if found_user && found_pass {
        info!("Using existing bitcoin.conf credentials");
        Some(config)
    } else {
        None
    }
}

/// Write bitcoin.conf with optimal settings
/// Returns the config that was written (or read from existing file)
pub fn write_config(data_dir: &Path, config: &BitcoinConfig) -> Result<(), BitcoinError> {
    std::fs::create_dir_all(data_dir)?;

    let config_path = data_dir.join("bitcoin.conf");

    // Generate new config
    let content = format!(
        r#"# Bitcoin Core configuration
# Generated by btcminer

# Network
server=1
txindex=0
prune={}

# RPC
rpcuser={}
rpcpassword={}
rpcport={}
rpcallowip=127.0.0.1
rpcbind=127.0.0.1

# Performance (dbcache auto-calculated based on available RAM)
dbcache={}
maxmempool=300
mempoolexpiry=72

# Mining
blockmaxweight=4000000
"#,
        config.prune_size,
        config.rpc_user,
        config.rpc_password,
        config.rpc_port,
        config.dbcache
    );

    std::fs::write(&config_path, content)?;

    info!("Wrote bitcoin.conf to {:?}", config_path);
    Ok(())
}

/// Generate a cryptographically secure random alphanumeric string
pub fn generate_random_string(len: usize) -> String {
    const CHARSET: &[u8] = b"abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789";

    let mut bytes = vec![0u8; len];
    if getrandom::getrandom(&mut bytes).is_err() {
        // Fallback to timestamp-based if OS RNG fails (should not happen)
        use std::time::{SystemTime, UNIX_EPOCH};
        let seed = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .unwrap_or_default()
            .as_nanos();
        let mut state = seed;
        for byte in &mut bytes {
            state = state.wrapping_mul(6364136223846793005).wrapping_add(1);
            *byte = ((state >> 33) as usize % CHARSET.len()) as u8;
        }
        return bytes
            .iter()
            .map(|&i| CHARSET[i as usize] as char)
            .collect();
    }

    bytes
        .iter()
        .map(|&b| CHARSET[(b as usize) % CHARSET.len()] as char)
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;
    use tempfile::TempDir;

    #[test]
    fn test_generate_random_string_length() {
        let s = generate_random_string(16);
        assert_eq!(s.len(), 16);

        let s = generate_random_string(32);
        assert_eq!(s.len(), 32);
    }

    #[test]
    fn test_generate_random_string_alphanumeric() {
        let s = generate_random_string(100);
        assert!(s.chars().all(|c| c.is_ascii_alphanumeric()));
    }

    #[test]
    fn test_generate_random_string_different_each_time() {
        // Small chance of collision, but very unlikely
        let s1 = generate_random_string(32);
        std::thread::sleep(std::time::Duration::from_millis(1));
        let s2 = generate_random_string(32);
        assert_ne!(s1, s2);
    }

    #[test]
    fn test_calculate_dbcache_in_range() {
        let dbcache = calculate_dbcache();
        assert!(dbcache >= 450, "dbcache {} should be >= 450", dbcache);
        assert!(dbcache <= 16384, "dbcache {} should be <= 16384", dbcache);
    }

    #[test]
    fn test_write_config_creates_file() {
        let dir = TempDir::new().unwrap();
        let config = BitcoinConfig {
            rpc_user: "testuser".to_string(),
            rpc_password: "testpass".to_string(),
            rpc_port: 8332,
            prune_size: 10000,
            dbcache: 1024,
        };

        write_config(dir.path(), &config).unwrap();

        let config_path = dir.path().join("bitcoin.conf");
        assert!(config_path.exists());

        let content = std::fs::read_to_string(&config_path).unwrap();
        assert!(content.contains("rpcuser=testuser"));
        assert!(content.contains("rpcpassword=testpass"));
        assert!(content.contains("server=1"));
        assert!(content.contains("prune=10000"));
    }

    #[test]
    fn test_read_existing_config() {
        let dir = TempDir::new().unwrap();
        let config_path = dir.path().join("bitcoin.conf");
        std::fs::write(
            &config_path,
            "rpcuser=existinguser\nrpcpassword=existingpass\nrpcport=18332\n",
        )
        .unwrap();

        let config = read_existing_config(dir.path()).unwrap();
        assert_eq!(config.rpc_user, "existinguser");
        assert_eq!(config.rpc_password, "existingpass");
        assert_eq!(config.rpc_port, 18332);
    }

    #[test]
    fn test_read_existing_config_partial() {
        let dir = TempDir::new().unwrap();
        let config_path = dir.path().join("bitcoin.conf");
        // Only user, no password
        std::fs::write(&config_path, "rpcuser=u\n").unwrap();

        // Should return None - incomplete credentials
        assert!(read_existing_config(dir.path()).is_none());
    }

    #[test]
    fn test_read_existing_config_missing() {
        let dir = TempDir::new().unwrap();
        assert!(read_existing_config(dir.path()).is_none());
    }

    #[test]
    fn test_bitcoin_config_default() {
        let config = BitcoinConfig::default();
        assert_eq!(config.rpc_user.len(), 16);
        assert_eq!(config.rpc_password.len(), 32);
        assert_eq!(config.rpc_port, 8332);
        assert_eq!(config.prune_size, 10000);
        assert!(config.dbcache >= 450 && config.dbcache <= 16384);
    }
}
